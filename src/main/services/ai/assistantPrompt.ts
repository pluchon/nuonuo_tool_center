// 本地检索也有角色口吻，文案只依赖真实的检索结果。历史中保存选定的正文。
export function cardCaption(count: number, previous: string | undefined, mode: 'search' | 'similar' | 'refine'): string {
  let lines = count === 1
    ? ['喏，就这张，拿去看吧。', '行吧，顺手帮你翻出来了。', '诺，你要的在这儿。']
    : ['喏，都翻出来了，自己挑吧。', '一天天的就指望我翻，都在这儿了。', '行吧行吧，翻出来的都在下面了。']
  if (mode === 'similar') lines = ['顺着这张摸出几张像的，自己瞅瞅吧。', '差不多感觉的都在这儿了。']
  if (mode === 'refine') lines = ['事儿真多，按你刚说的又筛了一遍。', '行了，从刚才那堆里又挑出来这些。']
  return lines[(lines.indexOf(previous ?? '') + 1) % lines.length]
}

