// 每张图附带的文字：本地线索（文件名、元信息）
export function lookTail(clues: LocalClues): string {
  const lines = ['[软件附注] 这张图的本地线索：', ...clues.notes.map((n) => `- ${n}`)]
  if (clues.source) {
    lines.push(`- 出处链接：${clues.source}`)
  }
  if (clues.photo) {
    lines.push('- 这是相机拍的照片，不用查出处。')
  }
  return lines.join('\n')
}
